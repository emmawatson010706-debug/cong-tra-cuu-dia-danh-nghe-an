const normalizeText = (value = '') =>
  String(value)
    .toLowerCase()
    .replace(/\s+/g, ' ')
    .trim();

const normalizeParent = (value = '') => normalizeText(value);

const getUnitNames = (place = {}) => {
  const arrays = [
    place.formerUnitsDetailed,
    place.oldUnitsDetailed,
    place.sourceUnitsDetailed,
    place.oldUnits,
    place.formerUnits,
    place.mergedFrom,
    place.sourceUnits,
    place.previousUnits
  ];

  const units = [];

  arrays.forEach((arr) => {
    if (!Array.isArray(arr)) return;

    arr.forEach((item) => {
      if (!item) return;

      if (typeof item === 'string') {
        units.push({
          name: item,
          parent: place.oldDistrict || place.parentBefore2025 || ''
        });
        return;
      }

      if (item.name) {
        units.push({
          name: item.name,
          parent: item.parent || item.oldDistrict || place.oldDistrict || place.parentBefore2025 || ''
        });
      }
    });
  });

  if (place.name) {
    units.push({
      name: place.name,
      parent: place.oldDistrict || place.parentBefore2025 || ''
    });
  }

  return units;
};

const sameUnit = (a = {}, b = {}) => {
  const nameA = normalizeText(a.name);
  const nameB = normalizeText(b.name);
  const parentA = normalizeParent(a.parent);
  const parentB = normalizeParent(b.parent);

  if (!nameA || !nameB) return false;
  if (nameA !== nameB) return false;

  // Nếu cả hai bên có parent thì bắt buộc parent phải trùng.
  // Chống lỗi: Phường Hưng Phúc - TP Vinh cũ bị kéo nhầm sang Xã Hưng Phúc - Huyện Hưng Nguyên cũ.
  if (parentA && parentB) return parentA === parentB;

  return true;
};

const resultUnitsOnly = (stage = {}) => {
  const units = [];

  if (stage.resultUnit) {
    units.push(stage.resultUnit);
  }

  // Chỉ dùng relatedUnits cho trường hợp đặc biệt đã khai báo rõ,
  // ví dụ cụm Cửa Lò sau khi nhập vào thành phố Vinh theo Nghị quyết 1243.
  if (Array.isArray(stage.relatedUnits)) {
    stage.relatedUnits.forEach((item) => {
      if (item) units.push(item);
    });
  }

  return units.filter(Boolean);
};

export function getAdministrativeTimeline(place = {}) {
  const units2025 = getUnitNames(place);
  const results = [];
  const seen = new Set();

  adminHistory2024.forEach((stage) => {
    const matched = units2025.some((unit) =>
      resultUnitsOnly(stage).some((stageUnit) => sameUnit(unit, stageUnit))
    );

    if (!matched) return;

    const key = stage.id || stage.description;
    if (seen.has(key)) return;

    seen.add(key);

    results.push({
      year: stage.year,
      title: stage.title,
      description: stage.description,
      source: stage.source,
      relatedUnit: stage.resultUnit?.name || stage.id
    });
  });

  return results;
}